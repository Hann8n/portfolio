// Exercises actual reloads, not only the saved JSON. All data and preferences stay local.
import assert from 'node:assert/strict';
import fs from 'node:fs';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright');
const browser=await chromium.launch();const page=await browser.newPage({viewport:{width:1280,height:800}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const campaign=fs.readFileSync('/tmp/gymtracker-qa-campaign.txt','utf8').trim();
const loaded=()=>page.waitForFunction(()=>document.querySelector('#appMetrics')?.hidden===false);
try {
  await page.goto('http://localhost:8788/admin');await loaded();
  await page.getByRole('tab',{name:'Campaigns',exact:true}).click();
  await page.locator('#creativeCampaign').selectOption(campaign);
  await page.locator('#analyticsPeriod').selectOption('90');await loaded();
  await page.locator('#adsSearch').fill('qa-campaign');
  await page.locator('[data-filter=live]').click();
  await page.locator('#calNext').click();
  const month=await page.locator('#calMonthLabel').innerText();
  await page.locator('#dashboardContent').evaluate(el=>el.scrollTop=240);
  await page.waitForTimeout(180);
  await page.reload();await loaded();await page.waitForTimeout(80);
  assert.equal(await page.locator('#tabCampaigns').getAttribute('aria-selected'),'true');
  assert.equal(await page.locator('#analyticsPeriod').inputValue(),'90');
  assert.equal(await page.locator('#creativeCampaign').inputValue(),campaign);
  assert.equal(await page.locator('#adsSearch').inputValue(),'qa-campaign');
  assert.equal(await page.locator('[data-filter=live]').getAttribute('class'),'status-filter active');
  assert.equal(await page.locator('#calMonthLabel').innerText(),month);
  assert.ok(await page.locator('#dashboardContent').evaluate(el=>el.scrollTop>=230));
  await page.getByRole('tab',{name:'Events',exact:true}).click();
  await page.locator('#eventCategory').selectOption('ads');
  await page.locator('#eventCampaign').selectOption(campaign);
  await page.waitForFunction(()=>document.querySelector('#eventReadout tbody tr'));
  await page.reload();await loaded();await page.waitForFunction(()=>document.querySelector('#eventReadout tbody tr'));
  assert.equal(await page.locator('#tabEvents').getAttribute('aria-selected'),'true');
  assert.equal(await page.locator('#eventCategory').inputValue(),'ads');
  assert.equal(await page.locator('#eventCampaign').inputValue(),campaign);
  assert.equal(await page.locator('#eventReadout tbody tr').count(),2);
  await page.getByRole('tab',{name:'Overview',exact:true}).click();
  await page.locator('#chartMetric').selectOption('event_opens');
  await page.reload();await loaded();
  assert.equal(await page.locator('#tabOverview').getAttribute('aria-selected'),'true');
  assert.equal(await page.locator('#chartMetric').inputValue(),'event_opens');
  const invalid=await browser.newPage();invalid.on('pageerror',e=>errors.push(e.message));
  await invalid.addInitScript(()=>localStorage.setItem('gymtracker.dashboard.v1',JSON.stringify({view:'bad',period:'-5',campaign:'deleted',eventCampaign:'deleted',eventCategory:'bad',calendarMonth:99,calendarYear:'bad'})));
  await invalid.goto('http://localhost:8788/admin');await invalid.waitForFunction(()=>document.querySelector('#appMetrics')?.hidden===false);
  assert.equal(await invalid.locator('#tabOverview').getAttribute('aria-selected'),'true');
  assert.equal(await invalid.locator('#analyticsPeriod').inputValue(),'7');
  assert.notEqual(await invalid.locator('#creativeCampaign').inputValue(),'deleted');
  assert.equal(await invalid.locator('#eventCampaign').inputValue(),'');
  assert.equal(await invalid.locator('#eventCategory').inputValue(),'all');
  await invalid.close();
  const corrupt=await browser.newPage();corrupt.on('pageerror',e=>errors.push(e.message));
  await corrupt.addInitScript(()=>localStorage.setItem('gymtracker.dashboard.v1','not json'));
  await corrupt.goto('http://localhost:8788/admin');await corrupt.waitForFunction(()=>document.querySelector('#appMetrics')?.hidden===false);
  assert.equal(await corrupt.locator('#analyticsPeriod').inputValue(),'7');await corrupt.close();
  const blocked=await browser.newPage();
  blocked.on('pageerror',e=>errors.push(e.message));
  await blocked.addInitScript(()=>{Storage.prototype.getItem=()=>{throw new Error('blocked')};Storage.prototype.setItem=()=>{throw new Error('blocked')};});
  await blocked.goto('http://localhost:8788/admin');
  await blocked.waitForFunction(()=>document.querySelector('#appMetrics')?.hidden===false);
  await blocked.getByRole('tab',{name:'Campaigns',exact:true}).click();
  assert.equal(await blocked.locator('#tabCampaigns').getAttribute('aria-selected'),'true');
  await blocked.close();
  assert.deepEqual(errors,[]);
  console.log('PASS: reload restores tab, period, campaign, search/status, calendar month, scroll, event filters and chart; deleted/stale/corrupt/blocked storage falls back safely');
} finally {await browser.close();}
